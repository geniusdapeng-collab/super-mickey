// ========== 经验包选择器 ==========
class ExperiencePackSelector {
  constructor() {
    this.packs = FPV_EXPERIENCE_PACKS.packs;
    this.index = FPV_EXPERIENCE_PACKS.index;
    this.constraints = FPV_EXPERIENCE_PACKS.systemConstraints;
  }

  /**
   * 根据ID获取经验包
   * @param {string} packId - 经验包ID
   * @returns {Object|null} 经验包对象
   */
  getPackById(packId) {
    return this.packs.find(p => p.id === packId) || null;
  }

  /**
   * 根据场景参数选择最适合的经验包
   * @param {Object} sceneParams - 场景参数
   * @param {string} sceneParams.sceneType - 场景类型
   * @param {string} sceneParams.subjectType - 主体类型
   * @param {string} sceneParams.tone - 情绪基调
   * @param {Array<string>} sceneParams.techniques - 需要的技法
   * @returns {Object} 推荐的经验包列表（按匹配度排序）
   */
  selectPack(sceneParams) {
    const { sceneType, subjectType, tone, techniques = [] } = sceneParams;
    
    // 计算每个经验包的匹配分数
    const scores = this.packs.map(pack => {
      let score = 0;
      
      // 场景类型匹配 +30
      if (pack.sceneType === sceneType) score += 30;
      
      // 主体类型匹配 +25
      if (pack.subjectType === subjectType) score += 25;
      
      // 情绪基调匹配 +20
      if (tone && pack.tags.some(tag => tag.includes(tone))) score += 20;
      
      // 技法匹配 +15每个
      techniques.forEach(tech => {
        if (pack.uniqueTechniques.includes(tech)) score += 15;
      });
      
      // 一镜到底适用性 +10
      if (pack.oneShotSuitable.length > 0) score += 10;
      
      return { pack, score };
    });
    
    // 按分数排序
    scores.sort((a, b) => b.score - a.score);
    
    return {
      topPick: scores[0],
      alternatives: scores.slice(1, 4),
      allScores: scores
    };
  }

  /**
   * 强制检查：是否包含一镜到底镜头
   * @param {Array} shots - 镜头列表
   * @returns {Object} 检查结果
   */
  validateOneShotMandatory(shots) {
    const oneShots = shots.filter(shot => 
      shot.type === 'one-shot' || 
      shot.cameraMovement?.includes('一镜到底') ||
      shot.description?.includes('单一连续镜头')
    );
    
    return {
      valid: oneShots.length >= 1,
      count: oneShots.length,
      oneShots: oneShots,
      error: oneShots.length < 1 ? '系统约束：每个片子必须包含至少1个"一镜到底"镜头' : null
    };
  }

  /**
   * 生成一镜到底镜头Prompt
   * @param {string} packId - 经验包ID
   * @param {Object} customizations - 定制化参数
   * @returns {string} 生成的Prompt
   */
  generateOneShotPrompt(packId, customizations = {}) {
    const pack = this.packs.find(p => p.id === packId);
    if (!pack) throw new Error(`未找到经验包: ${packId}`);
    
    const { subject = '主角', environment = '场景', action = '高速运动' } = customizations;
    
    // 基于经验包模板生成Prompt
    let prompt = pack.fullPrompt
      .replace(/蚂蚁|蜜蜂|苍蝇|蜻蜓|精灵|蝙蝠|滑雪者|婴儿/g, subject)
      .replace(/衣服|餐桌|儿童房|洞穴|冰川|超市|教室|博物馆|交易大厅|实验室/g, environment);
    
    return prompt;
  }
}

